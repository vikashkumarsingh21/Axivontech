import ExcelJS from "exceljs";

export interface ColumnDefinition {
  key: string;
  header: string;
  width?: number;
  type?: "text" | "number" | "currency" | "date" | "integer";
}

export interface SummaryInfo {
  title: string;
  generatedBy: string;
  generatedAt: string; // ISO or formatted Asia/Kolkata string
  exportType: string;
  filtersUsed: Record<string, any>;
  totalRows: number;
  isMasked: boolean;
  notes?: string[];
}

/**
 * Sanitizes a cell value to prevent Excel formula injection (CSV/DDE injection attacks).
 * Any string starting with =, +, -, @, \t, or \r is prefixed with a single quote.
 */
export function sanitizeCellValue(val: unknown): unknown {
  if (typeof val === "string") {
    if (val.length > 0 && ["=", "+", "-", "@", "\t", "\r"].includes(val.charAt(0))) {
      return `'${val}`;
    }
    return val;
  }
  return val;
}

/**
 * Creates and formats an ExcelJS Workbook with standard Axivon styling.
 */
export class AxivonExcelBuilder {
  private workbook: ExcelJS.Workbook;

  constructor() {
    this.workbook = new ExcelJS.Workbook();
    this.workbook.creator = "Axivon Technologies Administration";
    this.workbook.created = new Date();
  }

  /**
   * Adds the standardized Summary sheet as the first sheet.
   */
  public addSummarySheet(info: SummaryInfo): ExcelJS.Worksheet {
    const ws = this.workbook.addWorksheet("Summary", {
      properties: { tabColor: { argb: "FF0F172A" } },
      views: [{ showGridLines: true }],
    });

    ws.columns = [
      { key: "prop", width: 28 },
      { key: "val", width: 65 },
    ];

    // Title Row
    const titleRow = ws.addRow([info.title.toUpperCase(), ""]);
    ws.mergeCells("A1:B1");
    titleRow.height = 36;
    titleRow.getCell(1).font = { name: "Segoe UI", size: 16, bold: true, color: { argb: "FFFFFFFF" } };
    titleRow.getCell(1).fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: "FF0F172A" },
    };
    titleRow.getCell(1).alignment = { vertical: "middle", horizontal: "left", indent: 1 };

    ws.addRow([]); // Blank spacing

    const addMetadataRow = (label: string, value: string | number) => {
      const r = ws.addRow([label, sanitizeCellValue(value)]);
      r.height = 22;
      r.getCell(1).font = { name: "Segoe UI", size: 10, bold: true, color: { argb: "FF334155" } };
      r.getCell(2).font = { name: "Segoe UI", size: 10, color: { argb: "FF0F172A" } };
      r.getCell(1).alignment = { vertical: "middle" };
      r.getCell(2).alignment = { vertical: "middle" };
      r.getCell(1).border = { bottom: { style: "thin", color: { argb: "FFE2E8F0" } } };
      r.getCell(2).border = { bottom: { style: "thin", color: { argb: "FFE2E8F0" } } };
    };

    addMetadataRow("Export Type", info.exportType);
    addMetadataRow("Generated By", info.generatedBy);
    addMetadataRow("Generated At (Asia/Kolkata)", info.generatedAt);
    addMetadataRow("Total Records", info.totalRows);
    addMetadataRow(
      "Financial / PII Masking",
      info.isMasked ? "MASKED (Default Security Standard)" : "UNMASKED (Admin Password Authenticated)"
    );

    // Filters breakdown
    const filterEntries = Object.entries(info.filtersUsed).filter(
      ([, val]) => val !== undefined && val !== null && val !== "" && (Array.isArray(val) ? val.length > 0 : true)
    );

    if (filterEntries.length > 0) {
      ws.addRow([]);
      const fHeader = ws.addRow(["ACTIVE FILTERS APPLIED", ""]);
      fHeader.getCell(1).font = { name: "Segoe UI", size: 11, bold: true, color: { argb: "FF0F172A" } };

      for (const [key, val] of filterEntries) {
        const readableVal = Array.isArray(val) ? val.join(", ") : typeof val === "object" ? JSON.stringify(val) : String(val);
        addMetadataRow(`• ${key}`, readableVal);
      }
    }

    if (info.notes && info.notes.length > 0) {
      ws.addRow([]);
      const nHeader = ws.addRow(["SYSTEM COMPLIANCE NOTICES", ""]);
      nHeader.getCell(1).font = { name: "Segoe UI", size: 11, bold: true, color: { argb: "FF991B1B" } };
      for (const n of info.notes) {
        const nr = ws.addRow(["Notice", n]);
        nr.getCell(2).font = { name: "Segoe UI", size: 9, italic: true, color: { argb: "FF64748B" } };
      }
    }

    return ws;
  }

  /**
   * Adds a high-quality data sheet with frozen headers, autoFilter, auto-column-width,
   * currency formats, date formats, and formula-injection neutralization.
   */
  public addDataSheet(
    sheetName: string,
    columns: ColumnDefinition[],
    rows: Array<Record<string, any>>
  ): ExcelJS.Worksheet {
    const ws = this.workbook.addWorksheet(sheetName, {
      views: [{ state: "frozen", xSplit: 0, ySplit: 1, showGridLines: true }],
    });

    // Setup columns
    ws.columns = columns.map((col) => ({
      key: col.key,
      header: col.header,
      width: col.width || 18,
    }));

    // Style Header Row
    const headerRow = ws.getRow(1);
    headerRow.height = 30;
    headerRow.font = { name: "Segoe UI", size: 10, bold: true, color: { argb: "FFFFFFFF" } };
    headerRow.fill = {
      type: "pattern",
      pattern: "solid",
      fgColor: { argb: "FF0F172A" }, // Slate-900 / Navy
    };
    headerRow.alignment = { vertical: "middle", horizontal: "center", wrapText: true };

    // AutoFilter
    if (columns.length > 0) {
      ws.autoFilter = {
        from: { row: 1, column: 1 },
        to: { row: 1, column: columns.length },
      };
    }

    // Dynamic width accumulator
    const colMaxLengths: Record<string, number> = {};
    columns.forEach((col) => {
      colMaxLengths[col.key] = col.header.length;
    });

    // Populate rows
    rows.forEach((row, rowIndex) => {
      const rowValues: any = {};

      columns.forEach((col) => {
        const rawVal = row[col.key];

        if (rawVal === undefined || rawVal === null) {
          rowValues[col.key] = "";
          return;
        }

        if (col.type === "currency" && typeof rawVal === "number") {
          rowValues[col.key] = rawVal;
        } else if (col.type === "integer" && typeof rawVal === "number") {
          rowValues[col.key] = Math.round(rawVal);
        } else if (col.type === "date") {
          const d = rawVal instanceof Date ? rawVal : new Date(rawVal);
          rowValues[col.key] = isNaN(d.getTime()) ? String(rawVal) : d;
        } else {
          rowValues[col.key] = sanitizeCellValue(rawVal);
        }

        // Measure text length for column width
        const strLen = String(rowValues[col.key]).length;
        if (strLen > colMaxLengths[col.key]) {
          colMaxLengths[col.key] = strLen;
        }
      });

      const excelRow = ws.addRow(rowValues);
      excelRow.height = 20;

      // Subtle zebra striping
      const isEven = rowIndex % 2 === 0;
      const zebraColor = isEven ? "FFFFFFFF" : "FFF8FAFC";

      columns.forEach((col, colIdx) => {
        const cell = excelRow.getCell(colIdx + 1);
        cell.font = { name: "Segoe UI", size: 9.5, color: { argb: "FF0F172A" } };
        cell.fill = {
          type: "pattern",
          pattern: "solid",
          fgColor: { argb: zebraColor },
        };
        cell.border = {
          bottom: { style: "thin", color: { argb: "FFE2E8F0" } },
          right: { style: "thin", color: { argb: "FFF1F5F9" } },
        };

        if (col.type === "currency") {
          cell.numFmt = "[$₹-en-IN] #,##0.00";
          cell.alignment = { horizontal: "right", vertical: "middle" };
        } else if (col.type === "integer") {
          cell.numFmt = "#,##0";
          cell.alignment = { horizontal: "right", vertical: "middle" };
        } else if (col.type === "date") {
          cell.numFmt = "yyyy-mm-dd hh:mm";
          cell.alignment = { horizontal: "center", vertical: "middle" };
        } else {
          cell.alignment = { vertical: "middle" };
        }
      });
    });

    // Apply calculated column widths with min/max bounds
    columns.forEach((col, idx) => {
      const maxLen = colMaxLengths[col.key] || 12;
      const computedWidth = Math.min(Math.max(maxLen + 4, 14), 50);
      ws.getColumn(idx + 1).width = computedWidth;
    });

    return ws;
  }

  /**
   * Generates the binary Excel buffer.
   */
  public async writeToBuffer(): Promise<Buffer> {
    const uint8Array = await this.workbook.xlsx.writeBuffer();
    return Buffer.from(uint8Array);
  }
}

/**
 * Builds CSV content safely with formula injection protection and RFC 4180 escaping.
 */
export function buildCsvContent(columns: ColumnDefinition[], rows: Array<Record<string, any>>): string {
  const escapeCsv = (val: unknown): string => {
    if (val === null || val === undefined) return "";
    let str = String(sanitizeCellValue(val));
    if (str.includes('"') || str.includes(",") || str.includes("\n") || str.includes("\r")) {
      str = `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  };

  const headerLine = columns.map((c) => escapeCsv(c.header)).join(",");
  const dataLines = rows.map((row) =>
    columns.map((c) => escapeCsv(row[c.key])).join(",")
  );

  return [headerLine, ...dataLines].join("\r\n");
}
